// Regenerates apps/desktop/src/main/tray-icon.ts (a 32x32 tray icon embedded as
// a data URL so packaging needs no extra asset files). Pure Node, no deps:
//   node apps/desktop/scripts/generate-tray-icon.mjs
// Tweak `bg`/`fg` or the glyph below and rerun; the emitted file carries a
// do-not-edit header.
import { deflateSync } from 'node:zlib'
import { writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const S = 32 // raster size; the OS scales it down for 16px trays
const SS = 4 // supersampling factor for smooth edges
const bg = [232, 102, 60] // brand orange
const fg = [255, 255, 255]
const radius = 7

const insideRounded = (x, y) => {
  const cx = Math.min(Math.max(x, radius), S - radius)
  const cy = Math.min(Math.max(y, radius), S - radius)
  const dx = x - cx
  const dy = y - cy
  return dx * dx + dy * dy <= radius * radius
}
const distSeg = (px, py, ax, ay, bx, by) => {
  const abx = bx - ax
  const aby = by - ay
  const t = Math.max(0, Math.min(1, ((px - ax) * abx + (py - ay) * aby) / (abx * abx + aby * aby)))
  return Math.hypot(px - (ax + abx * t), py - (ay + aby * t))
}
// White check mark inside the rounded square.
const inCheck = (x, y) =>
  distSeg(x, y, 9, 16.5, 14, 21.5) <= 2.2 || distSeg(x, y, 14, 21.5, 23.5, 10.5) <= 2.2

const px = new Uint8Array(S * S * 4)
for (let y = 0; y < S; y++) {
  for (let x = 0; x < S; x++) {
    let bgCount = 0
    let fgCount = 0
    for (let sy = 0; sy < SS; sy++) {
      for (let sx = 0; sx < SS; sx++) {
        const X = x + (sx + 0.5) / SS
        const Y = y + (sy + 0.5) / SS
        if (inCheck(X, Y)) fgCount++
        else if (insideRounded(X, Y)) bgCount++
      }
    }
    const total = SS * SS
    const aBg = bgCount / total
    const aFg = fgCount / total
    const i = (y * S + x) * 4
    px[i] = Math.round(fg[0] * aFg + bg[0] * aBg)
    px[i + 1] = Math.round(fg[1] * aFg + bg[1] * aBg)
    px[i + 2] = Math.round(fg[2] * aFg + bg[2] * aBg)
    px[i + 3] = Math.round(255 * (aBg + aFg))
  }
}

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c
})
const crc32 = buf => {
  let c = 0xffffffff
  for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}
const chunk = (type, data) => {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body))
  return Buffer.concat([len, body, crc])
}
const ihdr = Buffer.alloc(13)
ihdr.writeUInt32BE(S, 0)
ihdr.writeUInt32BE(S, 4)
ihdr[8] = 8
ihdr[9] = 6
const raw = Buffer.alloc(S * (S * 4 + 1))
for (let y = 0; y < S; y++) {
  Buffer.from(px.buffer, y * S * 4, S * 4).copy(raw, y * (S * 4 + 1) + 1)
}
const png = Buffer.concat([
  Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
  chunk('IHDR', ihdr),
  chunk('IDAT', deflateSync(raw)),
  chunk('IEND', Buffer.alloc(0)),
])
const target = resolve(dirname(fileURLToPath(import.meta.url)), '../src/main/tray-icon.ts')
writeFileSync(target, [
  '// Generated by apps/desktop/scripts/generate-tray-icon.mjs — do not edit by hand.',
  `export const TRAY_ICON_DATA_URL='data:image/png;base64,${png.toString('base64')}'`,
  '',
].join('\n'))
console.log(`wrote ${target} (${png.length} png bytes)`)
